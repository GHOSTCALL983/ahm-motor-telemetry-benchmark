"""B8 - generate results/KEY_RESULTS.md and results/tables/key_numbers.json.

Every number in KEY_RESULTS.md is computed here from the result tables, so the
summary cannot drift from the data. Re-run after any analysis is re-run.
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common import RESULTS, TABLES, TRAINED_MODELS  # noqa: E402

OP_H = {"vibration": 3, "temperature": 15}


def main():
    rl = pd.read_csv(TABLES / "b02_run_level.csv")
    tests = pd.read_csv(TABLES / "b02_tests.csv")
    rec = pd.read_csv(TABLES / "b03_recal_run_level.csv")
    rect = pd.read_csv(TABLES / "b03_recal_tests.csv")
    oc = pd.read_csv(TABLES / "b04_overconfidence_by_model.csv")
    cor = pd.read_csv(TABLES / "b05_correlations.csv")
    fl = pd.read_csv(RESULTS / "audit" / "a04_floor_summary.csv")
    K, L = {}, []
    op = rl[rl.h == rl.kind.map(OP_H)]
    L.append("# Key results (generated by code/analysis/b08_key_results.py - do not edit by hand)\n")
    L.append("Unit of analysis: run = one (dataset, target) pair; 45 runs = 9 datasets x 5 targets "
             "(27 vibration, 18 temperature). Operating horizons fixed by the original study before this "
             "analysis: vibration h=3 min, temperature h=15 min (cumulative MSE over steps 1..h). "
             "Every method is scored at the same 400 origins per run (5 folds x 80).\n")
    for kind in ("vibration", "temperature"):
        g = op[op.kind == kind]
        n = g.run.nunique()
        tr = g[g.method.isin(TRAINED_MODELS)]
        beat = tr.groupby("method").beats_best_naive.sum().sort_values(ascending=False)
        med = g.groupby("method").skill_vs_best_naive.median().sort_values(ascending=False)
        K[kind] = dict(n_runs=n, trained_beating_naive_in_majority=int((beat > n / 2).sum()),
                       beats=beat.astype(int).to_dict(), median_skill=med.round(4).to_dict())
        L.append(f"\n## {kind.capitalize()} ({n} runs, h={OP_H[kind]})\n")
        L.append(f"- Trained models beating the strongest naive baseline in a majority of runs: "
                 f"{K[kind]['trained_beating_naive_in_majority']} of 13 "
                 f"({', '.join(f'{m} {v}/{n}' for m, v in beat.items() if v > 0)}).")
        L.append("- Median skill vs strongest naive (top 8): " +
                 "; ".join(f"{m} {v:+.3f}" for m, v in med.head(8).items()) + ".")
        tt = tests[tests.kind == kind]
        for m in ("Ensemble-Mean-13", "Ridge-Univariate", "Ridge-Sensors", "ChronosBolt-Small", "Chronos2",
                  "Chronos2-Sensors"):
            for ref in ("TiDE", "median trained model"):
                r = tt[(tt.method == m) & (tt.reference == ref)]
                if r.empty:
                    continue
                r = r.iloc[0]
                L.append(f"- {m} vs {ref}: median MSE ratio {r.median_mse_ratio:.3f}, method better in "
                         f"{int(r.runs_method_better)}/{int(r.n_runs)} runs, Wilcoxon p={r.p_wilcoxon:.2g} "
                         f"(Holm {r.p_holm:.2g}).")
        for v in ("shrink", "affine", "anchored"):
            r = rect[(rect.kind == kind) & (rect.variant == v)].iloc[0]
            K[kind][f"recal_{v}"] = dict(median_ratio=round(float(r.median_ratio), 4),
                                         runs_improved=int(r.runs_improved), p=float(r.p_wilcoxon))
            L.append(f"- Causal recalibration '{v}' of the 13 trained models (folds 2-5): median MSE ratio "
                     f"{r.median_ratio:.3f}, improved in {int(r.runs_improved)}/{int(r.n)} runs, p={r.p_wilcoxon:.2g}.")
        # scope of the anchored recalibration: per model, and against the best simple method
        rk = rec[rec.kind == kind]
        tide = rk[(rk.method == "TiDE") & (rk.variant == "anchored")].ratio_vs_raw
        ridge_r = rk[(rk.method == "Ridge-Univariate") & (rk.variant == "anchored")].ratio_vs_raw
        anc = rk[(rk.family == "trained") & (rk.variant == "anchored")].pivot(index="run", columns="method",
                                                                               values="mse_folds2to5")
        ridge = rk[(rk.method == "Ridge-Univariate") & (rk.variant == "raw")].set_index("run").mse_folds2to5
        beat = anc.lt(ridge, axis=0).sum()
        hind = anc.min(axis=1) / ridge
        K[kind]["recal_anchored_scope"] = dict(tide_median=round(float(tide.median()), 4), tide_improved=int((tide < 1).sum()),
                                               models_beating_ridge_majority=[m for m, v in beat.items() if v > len(ridge) / 2],
                                               hindsight_best_vs_ridge=round(float(hind.median()), 4),
                                               hindsight_best_better=int((hind < 1).sum()))
        L.append(f"- Anchored recalibration, scope: TiDE alone {tide.median():.3f} (improved in {int((tide < 1).sum())}/"
                 f"{len(tide)} runs); Ridge-Univariate alone {ridge_r.median():.3f}. After recalibration, trained models "
                 f"beating raw Ridge-Univariate (folds 2-5) in a majority of runs: "
                 f"{', '.join(f'{m} {int(v)}/{len(ridge)}' for m, v in beat.items() if v > len(ridge) / 2) or 'none'}. "
                 f"Best recalibrated trained model per run, picked with hindsight on the test folds: "
                 f"{hind.median():.3f}x ridge, better in {int((hind < 1).sum())}/{len(ridge)} runs.")
        o = oc[(oc.kind == kind) & (oc.family == "trained")]
        L.append(f"- Overconfidence sd_ratio/r of trained models (median over runs): "
                 f"{o.median_overconf.min():.2f} ({o.loc[o.median_overconf.idxmin(), 'method']}) to "
                 f"{o.median_overconf.max():.2f} ({o.loc[o.median_overconf.idxmax(), 'method']}).")
        K[kind]["overconf_range"] = [round(float(o.median_overconf.min()), 3), round(float(o.median_overconf.max()), 3)]
    L.append("\n## Predictability score (lambda) - within channel kind\n")
    for _, r in cor[(cor.scope != "all") & (cor.score == "lambda_uncapped")].iterrows():
        L.append(f"- {r.scope}: lambda vs {r.outcome}: Spearman {r.spearman:+.2f} (p={r.p:.2g}, n={int(r.n)}).")
    L.append("\n## Floor-aware training (iteration 1, 26 targets, unit = target)\n")
    for _, r in fl.iterrows():
        L.append(f"- {r.model}: median change {r.median_delta_pct:+.2f}% MSE, improved {int(r.targets_improved)}"
                 f"/{int(r.n_targets)} targets, Wilcoxon p={r.p_wilcoxon:.2g}.")
    sens = pd.read_csv(TABLES / "b06_sensitivity_summary.csv")
    kept = pd.read_csv(TABLES / "b06_origins_kept.csv")
    L.append("\n## Sensitivity: forecasts touching flagged anomalies removed (rules in b06)\n")
    L.append(f"- Origins kept: {int(kept.kept.sum())} of {int(kept.origins.sum())} "
             f"({100 * kept.kept.sum() / kept.origins.sum():.1f}%); fewest in one run: {int(kept.kept.min())}.")
    for _, r in sens.iterrows():
        extra = (f", method better in {int(r.runs_method_better)}/{int(r.n_runs)} runs, p={r.p:.2g}"
                 if pd.notna(r.get("runs_method_better")) else f" (of 13; {int(r.n_runs)} runs)")
        L.append(f"- {r.kind}: {r.comparison} {r.value:.3f}{extra}.")
    tuning_section(L, K)
    divergence_section(L, K)
    seed_section(L, K)
    (RESULTS / "KEY_RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    (TABLES / "key_numbers.json").write_text(json.dumps(K, indent=2))
    print("\n".join(L))


def tuning_section(L, K):
    integ = pd.read_csv(TABLES / "b09_tuning_integrity.csv")
    sel = pd.read_csv(TABLES / "b09_tuning_selection.csv")
    rl = pd.read_csv(TABLES / "b09_tuning_run_level.csv")
    tt = pd.read_csv(TABLES / "b09_tuning_tests.csv")
    logs = pd.concat([pd.read_csv(f) for f in sorted((RESULTS / "tuning").glob("*.log.csv"))])
    fails = logs[logs.status != "ok"]
    L.append("\n## Hyperparameter check (b09; TiDE, TimeXer, NHITS x 8 configurations; 18 runs = 9 datasets x "
             "{self_x_ac, self_temperature_one}; selection on the validation block only)\n")
    L.append(f"- Integrity: test origins identical to the stored runs in {int(integ.origins_identical.sum())}/"
             f"{len(integ)} run-folds; max |truth difference| {integ.truth_max_abs_diff.max():.1g}; every "
             f"validation target precedes every test target: {bool(integ.val_before_test.all())}.")
    L.append(f"- Trainings: {len(logs)} run, {len(fails)} failed (" +
             "; ".join(f"{r.model} cfg{r.cfg} {r.fold}: {r.status.replace('FAILED: ', '')}" for r in fails.itertuples())
             + "); a failed configuration is not a candidate on that fold.")
    sp = sel.assign(r=sel.test_mse_cfg0_rerun / sel.test_mse_original_stored).groupby("model").r
    L.append("- Re-run of the ORIGINAL configuration vs the stored forecast (test MSE ratio per run-fold, min-max): "
             + "; ".join(f"{m} {sp.min()[m]:.2f}-{sp.max()[m]:.2f}" for m in ("TiDE", "NHITS", "TimeXer"))
             + ". Same settings and seed; GPU training of NHITS/TimeXer is not bit-reproducible.")
    z = sel.groupby("model").cfg_selected.apply(lambda v: (v == 0).mean())
    L.append("- Share of folds where validation selected the original configuration: "
             + "; ".join(f"{m} {100 * z[m]:.0f}%" for m in ("TiDE", "NHITS", "TimeXer")) + ".")
    K["tuning"] = {}
    for kind in ("vibration", "temperature"):
        L.append(f"- **{kind}** (9 runs):")
        for r in tt[tt.kind == kind].itertuples():
            L.append(f"  - {r.a} vs {r.b}: median MSE ratio {r.median_ratio_a_over_b:.3f}, {r.a} better in "
                     f"{r.runs_a_better}/{r.n_runs} runs, p={r.p_wilcoxon:.2g} (Holm {r.p_holm:.2g}).")
        piv = rl[rl.kind == kind].pivot(index="run", columns="method", values="mse")
        for a in ("TiDE-Tuned", "TimeXer-Tuned", "NHITS-Tuned", "TiDE-Oracle(test-selected, reference only)"):
            x = piv[a] / piv["Ridge-Univariate"]
            L.append(f"  - descriptive: {a} vs Ridge-Univariate: median MSE ratio {x.median():.3f}, "
                     f"{a} better in {int((x < 1).sum())}/9 runs.")
            K["tuning"][f"{kind}:{a}/Ridge-Univariate"] = round(float(x.median()), 4)


def divergence_section(L, K):
    cells = pd.read_csv(RESULTS / "audit" / "a07_divergent_cells.csv")
    rob = pd.read_csv(RESULTS / "audit" / "a07_robustness.csv")
    L.append("\n## Diverged trained-model forecasts (a07)\n")
    L.append("- Cells (model x run x fold, 2925 in total) with operating-horizon MSE above T x persistence: "
             + ", ".join(f"T=10: {int((cells.x_persistence > 10).sum())}" if t == 10 else
                         f"T={t}: {int((cells.x_persistence > t).sum())}" for t in (10, 20, 50))
             + f"; largest {cells.x_persistence.max():.0f}x ({cells.iloc[0].method}, {cells.iloc[0].run}, "
               f"{cells.iloc[0].fold}). By model (T=10): "
             + ", ".join(f"{m} {n}" for m, n in cells[cells.x_persistence > 10].method.value_counts().items()) + ".")
    keys = ["trained models beating best naive in a majority of runs",
            "Ridge-Univariate vs TiDE: median MSE ratio", "Ridge-Univariate vs median trained model: median MSE ratio",
            "Ensemble-Mean-13 vs TiDE: median MSE ratio", "Ensemble-Median-13 vs TiDE: median MSE ratio",
            "recalibration 'anchored': median MSE ratio vs raw"]
    for kind in ("vibration", "temperature"):
        g = rob[rob.kind == kind]
        parts = []
        for k in keys:
            v = g[g.claim == k].set_index("variant")
            a, b = v.iloc[0], v.iloc[1]
            fmt = (lambda r: f"{r.value:.0f}") if "majority" in k else \
                  (lambda r: f"{r.value:.3f} ({int(r.runs_better)}/{int(r.n_runs)})")
            parts.append(f"{k.replace(': median MSE ratio', '')}: {fmt(a)} -> {fmt(b)}")
        L.append(f"- {kind}, as reported -> diverged cells (>10x) removed: " + "; ".join(parts) + ".")


def seed_section(L, K):
    integ = pd.read_csv(TABLES / "b10_seed_integrity.csv")
    sp = pd.read_csv(TABLES / "b10_seed_spread.csv")
    co = pd.read_csv(TABLES / "b10_seed_conclusions.csv")
    L.append("\n## Training-seed variability (b10; seeds 42, 101, 202; 14 iteration-1 runs: 8 vibration, "
             "6 temperature; identical hardware and code)\n")
    L.append(f"- Integrity: {len(integ)} extra-seed runs, origins identical {bool(integ.origins_identical.all())}, "
             f"max |truth difference| {integ.truth_max_abs_diff.max():.1g}, NaN forecasts {int(integ.nan_cells.sum())}.")
    for kind in ("vibration", "temperature"):
        g = sp[sp.kind == kind].set_index("model")
        a = g.loc["ALL 13"]
        mods = g.drop("ALL 13").sort_values("median_cv")
        L.append(f"- {kind}: seed CV of a model's MSE, median over runs: all 13 models {a.median_cv:.3f} "
                 f"(TiDE {g.loc['TiDE', 'median_cv']:.3f}; largest {mods.index[-1]} {mods.median_cv.iloc[-1]:.3f}); "
                 f"worst max/min over seeds {a.worst_max_over_min:.2f}. Seed 42 is the best of the three in "
                 f"{100 * a.share_seed42_best:.0f}% of run x model cells (33% expected), mean rank "
                 f"{a.mean_seed42_rank:.2f} (2 expected).")
        for r in co[co.kind == kind].itertuples():
            L.append(f"  - {'seed ' + r.seed if r.seed != 'seed-mean' else 'mean forecast over the 3 seeds'}: trained models beating best naive in a majority of runs "
                     f"{r.trained_beating_best_naive_in_majority} ({r.models_beating}); Ridge-Univariate vs TiDE "
                     f"{r.ridge_vs_tide_median_ratio:.3f} (ridge better {r.ridge_better_than_tide}/{r.n_runs}); vs median "
                     f"trained {r.ridge_vs_median_trained_ratio:.3f} ({r.ridge_better_than_median_trained}/{r.n_runs}); "
                     f"TiDE best trained model {r.tide_best_trained_model_runs}/{r.n_runs}; anchored recalibration "
                     f"{r.anchored_median_ratio:.3f} ({r.anchored_runs_improved}/{r.n_runs} improved).")
        K.setdefault("seeds", {})[kind] = co[co.kind == kind].round(4).to_dict("records")


if __name__ == "__main__":
    main()
